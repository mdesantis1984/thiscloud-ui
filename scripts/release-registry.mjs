const versionPattern = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;
const digestPattern = /^[a-f0-9]{64}$/;

export function validateReleaseRegistry(releaseChecksums, { version, digest, baselineChecksums } = {}) {
  if (!releaseChecksums || Array.isArray(releaseChecksums) || typeof releaseChecksums !== 'object') {
    throw new Error('Release checksum registry must be a JSON object.');
  }

  for (const [registeredVersion, registeredDigest] of Object.entries(releaseChecksums)) {
    if (!versionPattern.test(registeredVersion) || !digestPattern.test(registeredDigest)) {
      throw new Error(`Invalid release checksum entry: ${registeredVersion}`);
    }
  }

  if (baselineChecksums) {
    for (const [registeredVersion, registeredDigest] of Object.entries(baselineChecksums)) {
      if (releaseChecksums[registeredVersion] !== registeredDigest) {
        throw new Error(`Release checksum registry is append-only; ${registeredVersion} cannot change or be removed.`);
      }
    }
  }

  const registeredDigest = releaseChecksums[version];
  if (!registeredDigest) {
    throw new Error(`No immutable checksum is registered for @thiscloud/ui-web ${version}.`);
  }
  if (digest && digest !== registeredDigest) {
    throw new Error(`Generated bytes do not match the registered checksum for ${version}; bump the package version.`);
  }

  return registeredDigest;
}
